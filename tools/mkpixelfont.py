#!/usr/bin/env python3
"""Rasterize Silkscreen's pixel grid into src/pixelfont.rs.

The window draws its bitmap lettering itself, one rectangle per lit cell
snapped to whole device pixels, so it stays sharp at any display scale. This
script samples the centre of every 125-unit cell of each glyph outline.

    python3 tools/mkpixelfont.py Silkscreen-Regular.ttf Silkscreen-Bold.ttf > src/pixelfont.rs

Font: Silkscreen, Copyright 2001 The Silkscreen Project Authors, SIL Open Font
License 1.1 (fonts/OFL-Silkscreen.txt). The generated table is a format
conversion of that font and stays under the same licence.
"""
import sys
from fontTools.pens.pointInsidePen import PointInsidePen
from fontTools.ttLib import TTFont

CELL = 125      # font units per pixel
TOP = 5         # cap height in cells; row 0 is the top row of the caps
ROWS = 7        # five cap rows and two below the baseline
# Arrows are not in Silkscreen; drawn on the same grid (4 x 5 caps, 5-wide arrows).
EXTRA = {
    "→": ["..#..", "...#.", "#####", "...#.", "..#.."],
    "←": ["..#..", ".#...", "#####", ".#...", "..#.."],
    "↑": ["..#..", ".###.", "#.#.#", "..#..", "..#.."],
    "↓": ["..#..", "..#..", "#.#.#", ".###.", "..#.."],
    "·": [".....", ".....", "..#..", ".....", "....."],
}


# Silkscreen Bold's W fills its middle rows and reads as a solid block at 8 px;
# this open seven-column W replaces it (a legibility change, not Silkscreen's design).
BOLD_EXTRA = {
    "W": ["##...##", "##.#.##", "#######", "###.###", "##...##"],
}


def rasterize(path, extra=None):
    font = TTFont(path)
    glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
    out = {}
    for code in range(0x20, 0x7F):
        g = glyphs[cmap[code]]
        cols = round(g.width / CELL)
        rows = []
        for r in range(ROWS):
            y = (TOP - 1 - r) * CELL + CELL / 2
            bits = 0
            for c in range(cols):
                pen = PointInsidePen(glyphs, (c * CELL + CELL / 2, y))
                g.draw(pen)
                bits |= pen.getResult() << c
            rows.append(bits)
        out[chr(code)] = (cols, rows)
    for ch, art in {**EXTRA, **(extra or {})}.items():
        rows = [sum(1 << (c + 1) for c, p in enumerate(line) if p == "#") for line in art] + [0, 0]
        out[ch] = (len(art[0]) + 2, rows)
    return out


def rust_char(ch):
    if ch in "'\\":
        return "'\\" + ch + "'"
    return f"'{ch}'" if ch.isascii() else f"'\\u{{{ord(ch):04x}}}'"


def emit(name, table):
    print(f"pub static {name}: &[(char, u8, [u16; {ROWS}])] = &[")
    for ch, (cols, rows) in sorted(table.items()):
        print(f"    ({rust_char(ch)}, {cols}, [{', '.join(f'0x{r:03x}' for r in rows)}]),")
    print("];")


if __name__ == "__main__":
    regular, bold = rasterize(sys.argv[1]), rasterize(sys.argv[2], BOLD_EXTRA)
    print("// Generated by tools/mkpixelfont.py from Silkscreen (SIL OFL 1.1,")
    print("// fonts/OFL-Silkscreen.txt). Each row is a bit mask, bit 0 = leftmost cell;")
    print("// rows run from the cap top down, two rows below the baseline.")
    print(f"pub const ROWS: usize = {ROWS};")
    print(f"pub const CAP_ROWS: usize = {TOP};")
    emit("REGULAR", regular)
    emit("BOLD", bold)
